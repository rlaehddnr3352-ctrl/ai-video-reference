import html as H
for slug, (seo, faqs) in D.items():
    p = f"{ROOT}/{slug}.html"
    s = open(p, encoding="utf-8").read()
    if "\nseo:" not in s.split("-->", 1)[0]:
        s = s.replace("\ndesc:", f"\nseo: {seo}\ndesc:", 1)
    if 'class="faq"' not in s:
        items = "".join(f"\n  <h3>{H.escape(q)}</h3>\n  <p>{H.escape(a)}</p>" for q, a in faqs)
        s = s.rstrip() + f'\n\n<h2 id="faq">자주 묻는 질문</h2>\n<section class="faq">{items}\n</section>\n'
    open(p, "w", encoding="utf-8").write(s)
    print(slug, "ok")
